#!/usr/bin/env node
// Regenerate LVGL assets from checked-in SVG and subset OTF sources.
// npm install --prefix build/muyu-assets-tools --no-audit --no-fund --save-exact lv_font_conv@1.5.3 sharp@0.34.5
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(path.join(root, 'build/muyu-assets-tools/package.json'));
const sharp = require('sharp');
for (const [name, wanted] of [['lv_font_conv', '1.5.3'], ['sharp', '0.34.5']]) {
  if (require(`${name}/package.json`).version !== wanted) throw new Error(`Expected ${name}@${wanted}`);
}
const symbols = [...new Set([...readFileSync(path.join(root, 'assets/fonts/muyu-characters.txt'), 'utf8')].filter(c => !/\s/.test(c)))].join('');
for (const size of [16, 20]) {
  const args = [
    '--font', 'assets/fonts/muyu-noto-sans-sc-subset.otf', '--range', '0x20-0x7E', '--symbols', symbols,
    '--size', String(size), '--bpp', '4', '--format', 'lvgl', '--no-compress',
    '--lv-font-name', `muyu_font_${size}`, '--lv-include', 'lvgl.h',
    '--output', `assets/fonts/muyu_font_${size}.c`,
  ];
  execFileSync(path.join(root, 'build/muyu-assets-tools/node_modules/.bin/lv_font_conv'), args, { cwd: root, stdio: 'inherit' });
}
const svg = path.join(root, 'assets/images/muyu-woodfish.svg');
await sharp(svg).png().toFile(path.join(root, 'assets/images/muyu-woodfish.png'));
const { data, info } = await sharp(svg).flatten({ background: '#F6EEDC' }).removeAlpha().raw().toBuffer({ resolveWithObject: true });
if (info.width !== 154 || info.height !== 115 || info.channels !== 3) throw new Error('Unexpected image shape');
const bytes = [];
for (let i = 0; i < data.length; i += 3) {
  const pixel = ((data[i] >> 3) << 11) | ((data[i + 1] >> 2) << 5) | (data[i + 2] >> 3);
  bytes.push(pixel & 255, pixel >> 8);
}
const lines = [];
for (let i = 0; i < bytes.length; i += 16) lines.push('    ' + bytes.slice(i, i + 16).map(v => '0x' + v.toString(16).padStart(2, '0')).join(', ') + ',');
writeFileSync(path.join(root, 'assets/images/muyu_woodfish.c'), `// Generated by tools/generate_muyu_assets.mjs; original artwork, repository MIT license.\n#include "lvgl.h"\n\nstatic const uint8_t muyu_woodfish_pixels[] = {\n${lines.join('\n')}\n};\n\nconst lv_image_dsc_t muyu_woodfish = {\n    .header = {\n        .magic = LV_IMAGE_HEADER_MAGIC,\n        .cf = LV_COLOR_FORMAT_RGB565,\n        .flags = 0,\n        .w = 154,\n        .h = 115,\n        .stride = 308,\n    },\n    .data_size = sizeof(muyu_woodfish_pixels),\n    .data = muyu_woodfish_pixels,\n};\n`);
console.log(`Muyu image generated: ${bytes.length} bytes RGB565`);
